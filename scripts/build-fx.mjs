// Builds the effects layer of the glass redesign.
//
//   node scripts/build-fx.mjs
//
// 1. Generates static border-beam CSS for the placements Debrief uses
//    (light + dark) with border-beam's own generator, so no CSS engine ships.
// 2. Writes the spring easing tokens in extension/style.css from
//    liquid-gooey's spring compiler.
// 3. Bundles the vanilla fx runtime (orb, beam, goo, metal) per page with
//    esbuild into extension/fx/. No React, no remote code, no eval.
//
// Sources of the effects live in third_party/libraries-dev (MIT, Jakub Antalik;
// metal-fx also carries the Paper Shaders Apache-2.0 NOTICE).
import { build, transform } from 'esbuild';
import { mkdirSync, readFileSync, writeFileSync, statSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ext = join(root, 'extension');
const out = join(ext, 'fx');
const gen = join(root, 'fx', 'generated');
const tmp = join(root, 'fx', '.tmp');
mkdirSync(out, { recursive: true });
mkdirSync(gen, { recursive: true });
mkdirSync(tmp, { recursive: true });

// ---- Placements: one beam per job it does ------------------------------
// id: data-beam value; radius must match the CSS radius of the element.
export const PLACEMENTS = [
  { id: 'db-rec',   size: 'pulse-inner', variant: 'ocean',  radius: 16, staticColors: true,  why: 'popup: recording card, calm breathing' },
  { id: 'db-call',  size: 'md',          variant: 'sunset', radius: 12, staticColors: false, why: 'popup: Start button while a call is detected' },
  { id: 'db-write', size: 'md',          variant: 'ocean',  radius: 14, staticColors: false, why: 'minutes page: the job card while minutes are written' },
  { id: 'db-ask',   size: 'line',        variant: 'ocean',  radius: 14, staticColors: false, why: 'Ask box while it has focus or is answering' },
  { id: 'db-search', size: 'line',        variant: 'colorful', radius: 14, staticColors: false, why: 'any search or question field while it has focus or is working' },
  { id: 'db-test',  size: 'line',        variant: 'ocean',  radius: 14, staticColors: false, why: 'a settings/tour card while a key or connection test runs' },
];

// ---- 1 + 2: run the generators in Node -----------------------------------
const genEntry = join(tmp, 'gen-entry.ts');
writeFileSync(genEntry, `
import { generateBeamCSS, sizePresets, sizeThemePresets, getPulseDriverConfig } from '${join(root, 'third_party/libraries-dev/border-beam/src/styles').replace(/\\/g, '/')}';
import { resolveTransition } from '${join(root, 'third_party/libraries-dev/liquid-gooey/src/spring').replace(/\\/g, '/')}';
export function run(placements: any[]) {
  const css: Record<string, Record<string, string>> = {};
  const pulse: Record<string, any> = {};
  for (const p of placements) {
    for (const theme of ['light', 'dark'] as const) {
      const sz: any = sizePresets[p.size as keyof typeof sizePresets];
      const th: any = sizeThemePresets[p.size as keyof typeof sizeThemePresets][theme];
      const isPulse = p.size.startsWith('pulse');
      const duration = p.size === 'line' ? 3.1 : isPulse ? 2.3 : 1.96;
      const hueRange = p.size === 'line' ? 13 : 30;
      ((css[p.id] ||= { light: '', dark: '' }))[theme] += generateBeamCSS({
        id: p.id, borderRadius: p.radius, borderWidth: sz.borderWidth, duration,
        strokeOpacity: th.strokeOpacity, innerOpacity: th.innerOpacity, bloomOpacity: th.bloomOpacity,
        innerShadow: th.innerShadow, size: p.size, colorVariant: p.variant, staticColors: p.staticColors,
        brightness: th.brightness ?? 1.3, saturation: th.saturation, hueRange, theme,
        hairlineOpacity: th.hairlineOpacity, glowSize: 1,
      }) + '\\n';
      if (isPulse) (pulse[p.id] ||= {})[theme] = getPulseDriverConfig(p.size, theme, duration, hueRange, p.staticColors, p.id);
    }
  }
  (globalThis as any).CSS = { supports: () => true };
  const spring = resolveTransition('snappy').easing;
  const smooth = resolveTransition('smooth').easing;
  return { css, pulse, spring, smooth };
}`);
const genOut = join(tmp, 'gen.mjs');
await build({ entryPoints: [genEntry], bundle: true, platform: 'node', format: 'esm', outfile: genOut, logLevel: 'error' });
const { run } = await import(pathToFileURL(genOut).href + `?t=${Date.now()}`);
const g = run(PLACEMENTS);

const header = `/* Generated by scripts/build-fx.mjs from border-beam (MIT, Jakub Antalik). Do not edit. */\n`;
// One small stylesheet per page, holding only the beams that page uses.
const PAGE_BEAMS = { popup: ['db-rec', 'db-call', 'db-search'], mom: ['db-write', 'db-ask', 'db-search'], options: ['db-test'], welcome: ['db-test'], ask: ['db-ask', 'db-search'] };
const calmCss = `/* Effects stay off when the user asks for calm or solid surfaces */\n` +
  `@media (prefers-reduced-motion: reduce), (prefers-reduced-transparency: reduce), (forced-colors: active) {\n  [data-beam]::before, [data-beam]::after, [data-beam] [data-beam-bloom] { display: none !important; }\n}\n` +
  `html.solid [data-beam]::before, html.solid [data-beam]::after, html.solid [data-beam] [data-beam-bloom] { display: none !important; }\n`;
for (const [page, ids] of Object.entries(PAGE_BEAMS)) {
  const light = ids.map((i) => g.css[i].light).join('\n');
  const dark = ids.map((i) => g.css[i].dark).join('\n');
  const raw = light + `\n@media (prefers-color-scheme: dark) {\n${dark}\n}\n` + calmCss;
  const { code } = await transform(raw, { loader: 'css', minify: true, target: ['chrome116'] });
  writeFileSync(join(out, `beam-${page}.css`), header + code);
}
writeFileSync(join(gen, 'beam-pulse.json'), JSON.stringify(g.pulse));

// Spring tokens into style.css (between the --spring lines)
const stylePath = join(ext, 'style.css');
let style = readFileSync(stylePath, 'utf8');
style = style.replace(/--spring: linear\([^;]*\);/, `--spring: ${g.spring};`).replace(/--spring-smooth: linear\([^;]*\);/, `--spring-smooth: ${g.smooth};`);
writeFileSync(stylePath, style);

// ---- 3: bundle the runtime -----------------------------------------------
const pages = ['theme', 'popup', 'mom', 'options', 'welcome', 'ask'];
const entryPoints = Object.fromEntries(pages.map((p) => [p === 'theme' ? 'theme' : `fx-${p}`, join(root, 'fx/src/pages', `${p}.js`)]));
entryPoints.metal = join(root, 'fx/src/metal.js');
await build({
  entryPoints, outdir: out, bundle: true, format: 'iife', minify: true, target: ['chrome116'],
  legalComments: 'eof', logLevel: 'error', define: { 'process.env.NODE_ENV': '"production"' },
  banner: { js: '/* Debrief fx layer. Effects ported from Libraries.dev by Jakub Antalik (MIT); metal shader by Paper Design, Inc. (Apache-2.0). See NOTICE.md. */' },
});
rmSync(tmp, { recursive: true, force: true });

// ---- size report -----------------------------------------------------------
const report = ['file,bytes'];
for (const f of ['theme.js', 'fx-popup.js', 'fx-mom.js', 'fx-options.js', 'fx-welcome.js', 'fx-ask.js', 'metal.js', ...Object.keys(PAGE_BEAMS).map((p) => `beam-${p}.css`)]) {
  report.push(`${f},${statSync(join(out, f)).size}`);
}
writeFileSync(join(root, 'fx', 'size-report.csv'), report.join('\n') + '\n');
console.log(report.join('\n'));
